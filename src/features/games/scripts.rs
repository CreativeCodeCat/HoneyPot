//! The scripts `/hack` plays out: twenty ways to be denied and twenty ways to get in.
//!
//! Text can use these placeholders: `{user}`, `{guess}`, `{answer}`, `{stars}` (the password as
//! asterisks), `{session}`, `{short}` (the first part of the session ID), `{hash}`, `{id}`,
//! `{code}` and `{payout}` (what happened to the reward, granted scripts only).

pub struct Script {
    /// Centred at the top of the header box
    pub title: &'static str,
    pub header: &'static [&'static str],
    /// Startup lines; an empty status prints a plain log line
    pub boot: &'static [(&'static str, &'static str)],
    pub intel: (&'static str, &'static [(&'static str, &'static str)]),
    /// Log lines once the player joins
    pub attempt: &'static [&'static str],
    /// Checks with dotted leaders and statuses
    pub checks: &'static [(&'static str, &'static str)],
    pub verdict: &'static [(&'static str, &'static str)],
    pub notices: &'static [&'static str],
    pub progress: &'static [(u8, &'static str)],
    /// Centred in the result box
    pub banner: &'static str,
    pub result: &'static [(&'static str, &'static str)],
    pub closing: &'static [&'static str],
    /// Printed with `> ` in front; empty strings are blank lines
    pub message: &'static [&'static str],
    pub end: &'static [&'static str],
}

